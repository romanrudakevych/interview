// Regenerates src/data/resources.js from the yeahub catalog API.
//
// Run by hand (`node scripts/import-resources.mjs`) to refresh; it is not wired
// into predev/prebuild, which would make every build need the network.
//
// The endpoint is public (no auth) and paginated. `specializations=11` is the
// React Frontend Developer track — the same slice the questions and tasks were
// imported from, and all this app is about.

import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const API = "https://api.yeahub.ru/external-products/product?specializations=11";
const OUT = fileURLToPath(new URL("../src/data/resources.js", import.meta.url));

// A few source tags carry a trailing space ("Networks "), which would otherwise
// show up as a duplicate filter chip.
const clean = (s) => (typeof s === "string" ? s.trim() : "");

const items = [];
for (let page = 1; ; page++) {
  const res = await fetch(`${API}&page=${page}&limit=50`);
  if (!res.ok) throw new Error(`page ${page} -> HTTP ${res.status}`);
  const body = await res.json();
  items.push(...body.data);
  if (items.length >= body.total) break;
  if (body.data.length === 0) throw new Error(`empty page ${page} before reaching total`);
}

const resources = items
  .map((raw) => ({
    // The API's own UUID. Unlike questions and tasks (ids by array position),
    // this one is assigned upstream and survives a re-import.
    id: raw.id,
    name: clean(raw.name),
    description: clean(raw.description),
    url: raw.url,
    image: raw.imageSrc ?? null,
    type: clean(raw.type?.description) || "Материал",
    skills: (raw.skills ?? []).map((s) => clean(s.title)).filter(Boolean),
  }))
  // Sorted by name for a stable diff on re-import; leading quotes are ignored in
  // the key so «…» titles don't all cluster at the top.
  .sort((a, b) =>
    a.name.replace(/^[^\p{L}\p{N}]+/u, "").localeCompare(b.name.replace(/^[^\p{L}\p{N}]+/u, ""), "ru")
  );

// Only the values actually present become filter chips — a chip that can never
// match anything is dead UI.
const uniqSorted = (values) => [...new Set(values)].sort((a, b) => a.localeCompare(b, "ru"));
const types = uniqSorted(resources.map((r) => r.type));
const skills = uniqSorted(resources.flatMap((r) => r.skills));

const out = `// Useful IT resources from the yeahub catalog (https://app.yeahub.ru/wiki/resources),
// React Frontend Developer track. Generated by \`node scripts/import-resources.mjs\` —
// edit the script rather than this file.

export const RESOURCE_TYPES = ${JSON.stringify(types, null, 2).replace(/\n/g, "\n")};

export const RESOURCE_SKILLS = ${JSON.stringify(skills, null, 2)};

export const resources = [
${resources.map((r) => "  " + JSON.stringify(r) + ",").join("\n")}
];
`;

writeFileSync(OUT, out);
console.log(`wrote ${OUT}: ${resources.length} resources, ${types.length} types, ${skills.length} skills`);
